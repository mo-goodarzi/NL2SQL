"""Single source of truth for configuration.

Every tunable knob in the project lives here. That is deliberate: Step 4 of the
build plan asks you to change one thing at a time and re-measure, and that is
only credible if each change is a flag rather than a code edit. When you write
your evaluation report you should be able to say "run A had
``use_schema_retrieval=False``, run B had it ``True``, nothing else differed" --
and have that be literally true.

Usage::

    from config import settings
    print(settings.model, settings.max_retries)
"""

from __future__ import annotations

from functools import lru_cache
from pathlib import Path
from typing import Literal

from pydantic import Field, field_validator
from pydantic_settings import BaseSettings, SettingsConfigDict

# Repo root: this file is at <root>/src/config.py, so go up two levels.
PROJECT_ROOT = Path(__file__).resolve().parents[1]


class Settings(BaseSettings):
    """Typed application settings, loaded from environment or a .env file.

    Anything without a default is required; a missing value fails loudly at
    import time rather than halfway through a 50-question evaluation run.
    """

    model_config = SettingsConfigDict(
        env_file=PROJECT_ROOT / ".env",
        env_file_encoding="utf-8",
        extra="ignore",
        case_sensitive=False,
    )

    # ------------------------------------------------------------------
    # Provider credentials
    # ------------------------------------------------------------------
    llm_provider: Literal["anthropic", "openai"] = "openai"
    anthropic_api_key: str | None = None
    openai_api_key: str | None = None

    # ------------------------------------------------------------------
    # Database
    # ------------------------------------------------------------------
    db_path: Path = PROJECT_ROOT / "data" / "olist.db"
    csv_dir: Path = PROJECT_ROOT / "data" / "raw"

    # ------------------------------------------------------------------
    # Model selection
    # ------------------------------------------------------------------
    model: str = "gpt-4o-mini"
    embedding_model: str = "sentence-transformers/all-MiniLM-L6-v2"

    #: Always 0 for SQL generation. Non-deterministic output makes evaluation
    #: numbers wobble between runs, and you will not be able to tell whether a
    #: change helped or the sampler simply got lucky.
    temperature: float = 0.0

    # ------------------------------------------------------------------
    # Agent behaviour
    # ------------------------------------------------------------------
    #: How many times the agent may rewrite a failing query before giving up.
    #: This is the semantic self-correction cap, not network retries.
    max_retries: int = 3

    #: Hard ceiling on rows returned to the model and the UI. Protects the
    #: context window and keeps the demo readable.
    max_rows: int = 100

    #: Seconds before a query is aborted. Without this, one accidental
    #: cross join stalls an entire evaluation run.
    query_timeout_s: float = 10.0

    # ------------------------------------------------------------------
    # Step 4 experiment toggles
    #
    # Flip exactly one per evaluation run. The accuracy trajectory table in
    # your report is generated by sweeping these, so resist the temptation to
    # bundle two improvements into a single run.
    # ------------------------------------------------------------------
    use_self_correction: bool = True
    use_schema_retrieval: bool = False
    use_few_shot: bool = False

    #: Number of tables retrieved before foreign-key expansion, when
    #: ``use_schema_retrieval`` is on.
    schema_top_k: int = 4

    #: Include a few example values per column in the rendered schema. Helps
    #: the model match string formats (e.g. that order_status is 'delivered',
    #: not 'Delivered'), at the cost of a longer prompt.
    include_sample_values: bool = True
    sample_values_per_column: int = 3

    #: A second model call per question to turn the result into one sentence.
    #: Worth it in the demo, wasted in evaluation -- set to False for eval
    #: runs to halve cost per sweep. Read by ``nodes.explain``.
    explain_answers: bool = True

    # ------------------------------------------------------------------
    # Observability (Step 5) -- entirely optional, must fail soft
    # ------------------------------------------------------------------
    langfuse_public_key: str | None = None
    langfuse_secret_key: str | None = None
    langfuse_host: str = "https://cloud.langfuse.com"

    #: Free-text label attached to traces and evaluation reports, e.g.
    #: "v3_schema_retrieval". Set it per run so results stay comparable later.
    run_label: str = "dev"

    # ------------------------------------------------------------------
    # Derived values and checks
    # ------------------------------------------------------------------
    @field_validator("db_path", "csv_dir", mode="after")
    @classmethod
    def _resolve(cls, v: Path) -> Path:
        """Resolve relative paths against the repo root, not the shell's cwd.

        Without this, ``python -m eval.run_eval`` and ``uvicorn app.api:app``
        would look for the database in different places.
        """
        return v if v.is_absolute() else (PROJECT_ROOT / v).resolve()

    @property
    def read_only_uri(self) -> str:
        """SQLite URI that makes writes impossible at the driver level.

        Used by ``db.py``. This is the real safety guarantee; the SELECT-only
        check in ``guardrails.py`` is a second layer on top of it.
        """
        return f"file:{self.db_path}?mode=ro"

    @property
    def tracing_enabled(self) -> bool:
        return bool(self.langfuse_public_key and self.langfuse_secret_key)

    @property
    def active_flags(self) -> dict[str, object]:
        """The experiment configuration, for stamping onto reports and traces.

        Every evaluation report should embed this so a number can always be
        traced back to the exact setup that produced it.
        """
        return {
            "model": self.model,
            "temperature": self.temperature,
            "max_retries": self.max_retries,
            "use_self_correction": self.use_self_correction,
            "use_schema_retrieval": self.use_schema_retrieval,
            "schema_top_k": self.schema_top_k if self.use_schema_retrieval else None,
            "use_few_shot": self.use_few_shot,
            "include_sample_values": self.include_sample_values,
        }

    def require_api_key(self) -> str:
        """Return the key for the active provider, or explain what is missing.

        Called by ``llm.py`` rather than at import time, so that ``load_data.py``
        can build the database without any model credentials present.
        """
        key = (
            self.anthropic_api_key
            if self.llm_provider == "anthropic"
            else self.openai_api_key
        )
        if not key:
            var = f"{self.llm_provider.upper()}_API_KEY"
            raise RuntimeError(
                f"{var} is not set. Add it to {PROJECT_ROOT / '.env'} "
                f"(see .env.example) or export it in your shell."
            )
        return key

    def require_database(self) -> Path:
        """Fail with an actionable message if the database has not been built."""
        if not self.db_path.exists():
            raise FileNotFoundError(
                f"No database at {self.db_path}. Build it first:\n"
                f"    python scripts/load_data.py"
            )
        return self.db_path


@lru_cache(maxsize=1)
def get_settings() -> Settings:
    """Cached accessor, mainly so tests can clear the cache and override env."""
    return Settings()


#: Import this everywhere. Do not construct ``Settings()`` elsewhere -- a second
#: instance is how two parts of the system quietly end up on different configs.
settings = get_settings()
